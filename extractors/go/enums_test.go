package main

import (
	"slices"
	"testing"
)

// orderSource is a module with one enumeration and the ways code changes
// its state.
const orderSource = `package shop

type Status string

const (
	Pending  Status = "pending"
	Paid     Status = "paid"
	Shipped  Status = "shipped"
	Refunded Status = "refunded"
)

type Kind int

const Only Kind = 1

type Order struct{ Status Status }

func (o *Order) Pay() {
	if o.Status == Pending {
		o.Status = Paid
	}
}

func (o *Order) Advance(ok bool) {
	switch o.Status {
	case Paid:
		o.Status = Shipped
	case Shipped, Pending:
		o.Status = Refunded
	default:
		o.Status = Pending
	}
}

func (o *Order) Refund(ok bool) {
	switch {
	case ok && Shipped == o.Status:
		o.Status = Refunded
	}
	o.Status = Pending
}
`

// generatedSource declares an enumeration in a generated file.
const generatedSource = `// Code generated by oapi-codegen. DO NOT EDIT.

package shop

type Color string

const (
	Red  Color = "red"
	Blue Color = "blue"
)
`

// TestEnumFacts: an enumeration's values are listed in order, and every
// guarded assignment is a transition; an unguarded one, the default case,
// a one-constant type and a generated file's types are not.
func TestEnumFacts(t *testing.T) {
	m, dir := loadModule(t, "example.com/shop", map[string]string{
		"shop.go":      orderSource,
		"generated.go": generatedSource,
	})

	var enums, values, transitions []string
	for _, f := range EnumFacts(m.pkgs, m.fset, dir) {
		switch f.Kind {
		case "enum":
			enums = append(enums, f.Attrs["name"]+"@"+f.Source.Lines)
		case "enum_value":
			values = append(values, f.Attrs["name"]+"="+f.Attrs["value"])
		case "transition":
			transitions = append(transitions,
				f.Attrs["from"]+">"+f.Attrs["to"]+"@"+f.Source.Lines)
		}
	}
	cases := map[string]struct{ got, want []string }{
		"enums": {enums, []string{"shop.Status@3-3"}},
		"values": {values, []string{
			"Paid=paid", "Pending=pending", "Refunded=refunded", "Shipped=shipped",
		}},
		"transitions": {transitions, []string{
			"Paid>Shipped@26-27", "Pending>Paid@19-21", "Pending>Refunded@28-29",
			"Shipped>Refunded@28-29", "Shipped>Refunded@37-38",
		}},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			slices.Sort(tc.got)
			if !slices.Equal(tc.got, tc.want) {
				t.Errorf("got %v, want %v", tc.got, tc.want)
			}
		})
	}
}
