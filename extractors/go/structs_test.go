package main

import (
	"slices"
	"testing"
)

// accountSource declares structs with fields of every kind a condition
// can and cannot use.
const accountSource = `package bank

import "time"

type Tier string

type Account struct {
	Balance   int64
	Tier      Tier
	Frozen    bool
	ClosedAt  *time.Time
	OpenedAt  time.Time
	Owner     *string
	Tags      []string
	Limits    map[string]int
	Parent    *Account
	_         int
	Audit
	notify    func()
	nickname  string
}

type Audit struct{ Note string }

type Handlers struct {
	OnClose func()
}

type ID = Account
`

// generatedStruct is a struct of a generated file.
const generatedStruct = `// Code generated by protoc-gen-go. DO NOT EDIT.

package bank

type Wire struct{ Amount int }
`

// TestStructFacts: a struct lists its scalar, enumeration, time and
// pointer-to-scalar fields in declaration order, named and unexported
// alike; collections, structs, functions, embedded and blank fields are
// not listed, a struct without a listed field has no fact, nor has an
// alias or a generated file's struct.
func TestStructFacts(t *testing.T) {
	m, dir := loadModule(t, "example.com/bank", map[string]string{
		"bank.go":      accountSource,
		"generated.go": generatedStruct,
	})
	var got []string
	for _, f := range StructFacts(m.pkgs, m.fset, dir) {
		got = append(got, f.Attrs["name"]+"@"+f.Source.Lines+": "+f.Attrs["fields"])
	}
	want := []string{
		"bank.Account@7-21: Balance,Tier,Frozen,ClosedAt,OpenedAt,Owner,nickname",
		"bank.Audit@23-23: Note",
	}
	if !slices.Equal(got, want) {
		t.Errorf("got %q, want %q", got, want)
	}
}
